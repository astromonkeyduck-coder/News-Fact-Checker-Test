// Helper function to get icon by metric name
export function getMetricIcon(metricName) {
  const normalized = metricName.toLowerCase();
  if (normalized.includes('engagement')) return MetricIcons.engagements;
  if (normalized.includes('like')) return MetricIcons.likes;
  if (normalized.includes('share')) return MetricIcons.shares;
  if (normalized.includes('repost')) return MetricIcons.reposts;
  if (normalized.includes('follower')) return MetricIcons.followers;
  return MetricIcons.engagements; // default
}

















